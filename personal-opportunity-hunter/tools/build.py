#!/usr/bin/env python3
"""Regenerate derived files from data/opportunities.json (the single source of truth).

Usage:  python3 tools/build.py            # rebuild files
        python3 tools/build.py --stats    # also print summary statistics
Edit only data/opportunities.json; never hand-edit the generated files.
"""
import csv, json, sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DB = json.loads((ROOT / "data" / "opportunities.json").read_text(encoding="utf-8"))
OPPS = DB["opportunities"]
TODAY = date.fromisoformat(DB["meta"]["last_full_run"])
GEN = f"<!-- GENERATED by tools/build.py from data/opportunities.json on {TODAY}. Do not edit by hand. -->\n\n"


def total(o):
    return sum(o["score"].values())


def validate():
    ids = [o["id"] for o in OPPS]
    dup = {i for i in ids if ids.count(i) > 1}
    if dup:
        sys.exit(f"Duplicate ids: {dup}")
    names = [o["name"].lower() for o in OPPS]
    if len(set(names)) != len(names):
        sys.exit("Duplicate names")
    caps = DB["meta"]["score_weights"]
    for o in OPPS:
        for k, cap in caps.items():
            if not 0 <= o["score"][k] <= cap:
                sys.exit(f"{o['id']}: score {k} out of range")
        if o["deadline"] and date.fromisoformat(o["deadline"]) < TODAY and o["status"] == "OPEN NOW":
            sys.exit(f"{o['id']}: deadline passed but status OPEN NOW")


def opp_md(o, rank=None):
    s = o["score"]
    cov = "\n".join(f"  - {k.replace('_', ' ').title()}: {v}" for k, v in o["covered"].items())
    src = "\n".join(f"  - <{u}>" for u in o["sources"])
    head = f"### {rank}. {o['name']}" if rank else f"### {o['name']}"
    return f"""{head}

| Field | Detail |
|---|---|
| Category | {o['category']} |
| Organiser | {o['organiser']} |
| Official website | <{o['website']}> |
| Application URL | {o['apply_url']} |
| Location | {o['location']} |
| Event dates | {o['event_dates']} |
| Applications open | {o['opens'] or 'Not announced'} |
| Deadline | {o['deadline'] or 'Not announced'} |
| Deadline timezone | {o['deadline_tz']} |
| Results | {o['results']} |
| **Status** | **{o['status']}** |
| When relevant | {dict(india_now='Now, from India', germany_2027='After the move to Germany (Mar 2027+)', both='Now and after the move').get(o['phase'])} |
| Funding class | **{o['funding_class']}** |
| Reimbursement | {o['reimbursement']} |
| Est. personal cost | {o['est_personal_cost']} |
| Verification | {o['verification']} (last verified {o['last_verified']}) |
| **Score** | **{total(o)}/100** (funding {s['funding']}/30 · networking {s['networking']}/25 · relevance {s['relevance']}/20 · eligibility {s['eligibility']}/15 · international {s['international']}/10) |

- **Eligibility:** {o['eligibility']}
- **Indian citizen eligible:** {o['indian_eligible']}
- **International student eligible:** {o['intl_student_eligible']}
- **Eligibility notes / uncertainty:** {o['eligibility_notes']}
- **Funding details:** {o['funding_details']}
- **Expenses covered:**
{cov}
- **Networking:** {o['networking']}
- **Career value:** {o['career_value']}
- **Documents:** {o['documents']}
- **Selection criteria:** {o['selection']}
- **Recommended action:** {o['action']}
- **Sources:**
{src}
"""


def build_opportunities_md():
    out = [GEN, "# Opportunity Database\n\n",
           f"Total records: {len(OPPS)} active + {len(DB['excluded'])} excluded/flagged. ",
           "Verification legend: " + "; ".join(f"**{k}** = {v}" for k, v in DB["meta"]["verification_levels"].items()) + "\n\n"]
    by_cat = {}
    for o in OPPS:
        by_cat.setdefault(o["category"], []).append(o)
    for cat in sorted(by_cat):
        out.append(f"## {cat}\n\n")
        for o in sorted(by_cat[cat], key=total, reverse=True):
            out.append(opp_md(o) + "\n")
    out.append("## Excluded, ineligible or flagged\n\n| Item | Reason | Source |\n|---|---|---|\n")
    for e in DB["excluded"]:
        out.append(f"| {e['name']} | {e['reason']} | {e['source']} |\n")
    (ROOT / "opportunities.md").write_text("".join(out), encoding="utf-8")


def build_csv():
    cols = ["id", "name", "category", "organiser", "website", "apply_url", "location", "event_dates", "opens",
            "deadline", "deadline_tz", "results", "status", "phase", "eligibility", "indian_eligible",
            "intl_student_eligible", "eligibility_notes", "funding_class", "funding_details", "reimbursement",
            "est_personal_cost", "networking", "career_value", "documents", "selection", "verification",
            "last_verified", "action"]
    cov_keys = list(OPPS[0]["covered"].keys())
    with open(ROOT / "opportunities.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(cols + [f"covers_{k}" for k in cov_keys] +
                   ["score_funding", "score_networking", "score_relevance", "score_eligibility",
                    "score_international", "score_total", "sources"])
        for o in sorted(OPPS, key=total, reverse=True):
            w.writerow([o[c] if o[c] is not None else "" for c in cols] + [o["covered"][k] for k in cov_keys] +
                       list(o["score"].values()) + [total(o), " | ".join(o["sources"])])


def build_deadlines():
    dated = sorted([o for o in OPPS if o["deadline"] and date.fromisoformat(o["deadline"]) >= TODAY],
                   key=lambda o: o["deadline"])
    out = [GEN, f"# Upcoming Application Deadlines (as of {TODAY})\n\n",
           "Only confirmed future deadlines are in the first table. Previous-cycle dates are never shown as future deadlines.\n\n",
           "| Deadline | Days left | Timezone | Opportunity | Status | Funding | Score | Apply |\n|---|---|---|---|---|---|---|---|\n"]
    for o in dated:
        d = (date.fromisoformat(o["deadline"]) - TODAY).days
        out.append(f"| {o['deadline']} | {d} | {o['deadline_tz']} | {o['name']} | {o['status']} | {o['funding_class']} | {total(o)} | {o['apply_url']} |\n")
    soon = [o for o in OPPS if o["opens"] and date.fromisoformat(o["opens"]) > TODAY]
    if soon:
        out.append("\n## Applications opening soon (confirmed opening date)\n\n| Opens | Opportunity | Deadline |\n|---|---|---|\n")
        for o in sorted(soon, key=lambda o: o["opens"]):
            out.append(f"| {o['opens']} | {o['name']} | {o['deadline'] or 'Not announced'} |\n")
    und = [o for o in OPPS if not o["deadline"]]
    out.append("\n## Deadline not yet announced (watch list)\n\n| Opportunity | Status | Note |\n|---|---|---|\n")
    for o in sorted(und, key=total, reverse=True):
        out.append(f"| {o['name']} | {o['status']} | {o['eligibility_notes']} |\n")
    (ROOT / "deadlines.md").write_text("".join(out), encoding="utf-8")


def build_priority():
    ranked = sorted(OPPS, key=total, reverse=True)
    out = [GEN, "# Priority Opportunities (ranked by score)\n\n",
           "Score = funding 30 + networking 25 + relevance 20 + eligibility 15 + international 10. "
           "Eligibility is scored on your *current* realistic situation, so items you cannot apply to yet rank lower.\n\n",
           "| Rank | Score | Opportunity | Status | Funding | Deadline | Phase |\n|---|---|---|---|---|---|---|\n"]
    for i, o in enumerate(ranked, 1):
        out.append(f"| {i} | {total(o)} | {o['name']} | {o['status']} | {o['funding_class']} | {o['deadline'] or 'TBA'} | {o['phase']} |\n")
    out.append("\n## Top 15 in detail\n\n")
    for i, o in enumerate(ranked[:15], 1):
        out.append(opp_md(o, i) + "\n")
    (ROOT / "priority-opportunities.md").write_text("".join(out), encoding="utf-8")


def stats():
    c = lambda f: sum(1 for o in OPPS if f(o))
    print(f"Total active records: {len(OPPS)} (+{len(DB['excluded'])} excluded/flagged)")
    print("Open now:", c(lambda o: o["status"] == "OPEN NOW"))
    for cls in ["FULLY FUNDED", "TRAVEL FUNDED", "PARTIALLY FUNDED", "REIMBURSEMENT", "REGISTRATION ONLY", "UNKNOWN"]:
        print(f"  {cls}:", c(lambda o, cls=cls: o["funding_class"] == cls))
    print("Usable as Indian citizen (now or later):", c(lambda o: o["score"]["eligibility"] > 0))
    print("Relevant after move to Germany:", c(lambda o: o["phase"] in ("germany_2027", "both")))
    print("Verification:", {v: c(lambda o, v=v: o["verification"] == v) for v in DB["meta"]["verification_levels"]})


if __name__ == "__main__":
    validate()
    build_opportunities_md(); build_csv(); build_deadlines(); build_priority()
    if "--stats" in sys.argv:
        stats()
    print("Build OK")
